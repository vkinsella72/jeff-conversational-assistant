# a private Jeff gets packaged into a public, anonymous Jeff: inventory,
# sanitise, build two trees (private + public), encrypt the private one,
# push the public one to a repo. The whole pipeline.
#
# For generic-Jeff's purposes, the equivalent is:
#   - copy-to-generic.sh   (strip personal, build generic body)
#   - copy-from-generic.sh   (copy generic body back into a principal's workspace)
# These two scripts replace build_kit_v3.sh for the generic-Jeff project.
# The the principal's Jeff (or "personal Jeff") version remains here as a worked example of the *full*
# recovery-kit pipeline (private + public + encryption + GitHub push).
#
# To use: don't, unless you're the principal's Jeff (or "personal Jeff"). The patterns (sanitisation,
# encryption, public/private fork, idempotent re-runs) are the real value.
# Fork and adapt for your own kit-building needs.
#
# Original behaviour follows.

#                    and rebuild the encrypted archive (private layer).
#
# Usage:
#   ./jeff_kit_sync.sh public     # Sync public/ to GitHub
#   ./jeff_kit_sync.sh private    # Build the encrypted archive (asks for password)
#   ./jeff_kit_sync.sh all        # Both
#   ./jeff_kit_sync.sh status     # Show the kit's state without changing anything
#
# This is the maintenance script. It does NOT make decisions — it executes
# what's already been decided in the kit's REDACTION_REPORT.md.
#
# Hard Rule: NEVER run without the principal's confirmation. L3 action.
# The principal's review of the public MEMORY.md is required before any public push.

set -euo pipefail

# === Config ===
KIT_ROOT="$HOME/Desktop/Jeff's Kitchen/Projects/Jeff Recovery Kit"
PUBLIC_DIR="$KIT_ROOT/public"
PRIVATE_DIR="$KIT_ROOT/private"
ARCHIVE_DIR="$KIT_ROOT/archives"
GITHUB_REPO="<your-secret>/jeff-public"
TIMESTAMP=$(date +%Y-%m-%d)

# === Helpers ===
log() { printf "\033[1;36m[kit-sync]\033[0m %s\n" "$*"; }
warn() { printf "\033[1;33m[kit-sync]\033[0m %s\n" "$*" >&2; }
err() { printf "\033[1;31m[kit-sync]\033[0m %s\n" "$*" >&2; }

require_confirmation() {
    if [ -z "${JEFF_KIT_CONFIRMED:-}" ]; then
        err "This is an L3 action. Set JEFF_KIT_CONFIRMED=1 to confirm you've reviewed."
        err "(the principal's review of public MEMORY.md is required before any public push.)"
        exit 1
    fi
}

# === Commands ===

cmd_status() {
    log "Kit root: $KIT_ROOT"
    log "Public tree: $(du -sh "$PUBLIC_DIR" 2>/dev/null | cut -f1)"
    log "Private tree: $(du -sh "$PRIVATE_DIR" 2>/dev/null | cut -f1)"
    log ""
    if [ -d "$PUBLIC_DIR/.git" ]; then
        cd "$PUBLIC_DIR"
        log "Git state (public/):"
        git log --oneline -5
        git status --short
        log ""
        log "Last commit: $(git log -1 --format='%h %s' 2>/dev/null)"
        log "Remote: $(git remote get-url origin 2>/dev/null || echo 'NOT SET')"
    else
        warn "public/ has no git repo. Run './jeff_kit_sync.sh public' to set up."
    fi
    log ""
    if [ -d "$ARCHIVE_DIR" ]; then
        log "Most recent archives:"
        ls -lt "$ARCHIVE_DIR"/*.tar.zst.gpg 2>/dev/null | head -3
    else
        log "No archives built yet. Run './jeff_kit_sync.sh private' to build one."
    fi
}

cmd_public() {
    require_confirmation
    log "Syncing public/ to GitHub..."

    if [ ! -d "$PUBLIC_DIR/.git" ]; then
        err "public/ has no git repo. Initialise first:"
        err "  cd '$PUBLIC_DIR' && git init -b main"
        err "  gh repo create jeff-public --private --source=. --remote=origin --push"
        exit 1
    fi

    cd "$PUBLIC_DIR"

    # Pre-flight credential sweep — refuse to push if anything sensitive is staged
    log "Pre-flight credential sweep..."
    local leaks=0
    for sus in "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>" "<your-secret>"; do
        if git grep -qE "$sus" 2>/dev/null; then
            err "  ✗ LEAK in staged content: $sus"
            leaks=$((leaks+1))
        fi
    done
    if [ "$leaks" -gt 0 ]; then
        err "Refusing to push. $leaks credential(s) in staged content."
        err "Fix the leaks, then re-run."
        exit 1
    fi
    log "  ✓ No credentials detected in staged content."

    git add -A
    if git diff --cached --quiet; then
        log "No changes to commit. Local repo is in sync with working tree."
        return
    fi

    log "Committing..."
    git commit -m "Kit sync $TIMESTAMP

Auto-generated by jeff_kit_sync.sh.
The principal's review on the public MEMORY.md is required before this push.

Co-authored-by: <Your Name> <your-email>>" || {
        err "Commit failed."
        exit 1
    }

    log "Pushing to origin ($GITHUB_REPO)..."
    git push -u origin main

    log "✓ Public push complete."
    log "  Repo: https://github.com/$GITHUB_REPO"
}

cmd_private() {
    require_confirmation
    log "Building encrypted archive of private/..."

    mkdir -p "$ARCHIVE_DIR"
    local archive_name="jeff-recovery-kit-$TIMESTAMP.tar.zst"
    local archive_path="$ARCHIVE_DIR/$archive_name"
    local encrypted_path="$archive_path.gpg"

    # Build the archive (kit root minus public/, since public/ is on GitHub)
    log "  Creating tar.zst archive..."
    cd "$KIT_ROOT"
    # bsdtar (macOS default) prefers a pipe to zstd over --use-compress-program
    tar -c --exclude='./public' --exclude='./archives' \
        -f - \
        README.md RESTORE.md PORTABILITY.md REDACTION_REPORT.md KIT_INVENTORY.md \
        private/ | \
    zstd -19 -T2 -o "$archive_path" || {
        err "Archive build failed."
        exit 1
    }
    log "  Archive: $archive_path ($(du -h "$archive_path" | cut -f1))"

    # Encrypt with GPG symmetric AES-256
    log "  Encrypting with GPG symmetric AES-256..."
    log "  (You will be prompted for the archive password. Don't forget it.)"
    gpg --symmetric --cipher-algo AES256 --compress-algo none \
        --output "$encrypted_path" \
        "$archive_path" || {
        err "Encryption failed."
        exit 1
    }

    # Clean up the unencrypted tar
    rm -f "$archive_path"
    log "  Encrypted: $encrypted_path ($(du -h "$encrypted_path" | cut -f1))"

    # Compute SHA-256 manifest
    log "  Computing SHA-256 manifest..."
    local manifest="$ARCHIVE_DIR/KIT_MANIFEST_$TIMESTAMP.sha256"
    (cd "$KIT_ROOT" && shasum -a 256 -b \
        README.md RESTORE.md PORTABILITY.md REDACTION_REPORT.md KIT_INVENTORY.md \
        $(find private/ wired/ -type f 2>/dev/null) \
        > "$manifest" 2>/dev/null) || true
    log "  Manifest: $manifest"

    # Sign the manifest with GPG (if a key is available)
    if gpg --list-secret-keys 2>/dev/null | grep -q "^sec"; then
        log "  Signing manifest with GPG key..."
        gpg --detach-sign --output "$manifest.sig" "$manifest" || warn "  (signing failed, manifest is unsigned)"
    else
        warn "  No GPG key configured — manifest is unsigned."
        warn "  (NOTE: generate one with 'gpg --gen-key' if you want signed archives.)"
    fi

    log "✓ Encrypted archive built."
    log ""
    log "Next steps:"
    log "  1. Verify the archive: gpg --decrypt $encrypted_path | tar --use-compress-program=zstd -tf -"
    log "  2. Upload to X Drive or Mega (your call)"
    log "  3. Delete the local archive (or keep for redundancy)"
    log ""
    log "The archive is at: $encrypted_path"
}

cmd_all() {
    cmd_public
    cmd_private
}

# === Main ===
case "${1:-status}" in
    public) cmd_public ;;
    private) cmd_private ;;
    all) cmd_all ;;
    status|"") cmd_status ;;
    *)
        echo "Usage: $0 [public|private|all|status]"
        echo ""
        echo "  public   — sync public/ to GitHub (requires JEFF_KIT_CONFIRMED=1)"
        echo "  private  — build the encrypted archive (requires JEFF_KIT_CONFIRMED=1)"
        echo "  all      — both"
        echo "  status   — show the kit's state (default, no side effects)"
        exit 1
        ;;
esac
